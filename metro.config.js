// Metro config + a small dev-only middleware for Design Mode (see
// .claude/skills/kadabook-auth-screen and src/devtools/designMode).
//
// POST /__design/save { screen, values } rewrites src/designConfig/<screen>.ts
// with the posted values, which become the screen's new baked-in default the
// next time Metro Fast Refreshes. Only ever touches that one pure-data file —
// never a screen's component code.
const { getDefaultConfig } = require('expo/metro-config');
const fs = require('fs');
const path = require('path');

const config = getDefaultConfig(__dirname);

const DESIGN_CONFIG_DIR = path.join(__dirname, 'src', 'designConfig');
const SCREEN_NAME_RE = /^[a-zA-Z][a-zA-Z0-9]*$/;

function readBody(req) {
  return new Promise((resolve, reject) => {
    let data = '';
    req.on('data', (chunk) => {
      data += chunk;
      if (data.length > 1_000_000) reject(new Error('body too large'));
    });
    req.on('end', () => resolve(data));
    req.on('error', reject);
  });
}

function writeDesignConfig(screen, values) {
  const filePath = path.join(DESIGN_CONFIG_DIR, `${screen}.ts`);
  const varName = `${screen}Layout`;
  const contents =
    `// Auto-generated by Design Mode. Edit visually in the app, or by hand.\n` +
    `export const ${varName} = ${JSON.stringify(values, null, 2)} as const;\n`;
  fs.mkdirSync(DESIGN_CONFIG_DIR, { recursive: true });
  fs.writeFileSync(filePath, contents, 'utf8');
}

const originalEnhanceMiddleware = config.server?.enhanceMiddleware;

config.server = {
  ...config.server,
  enhanceMiddleware: (middleware, metroServer) => {
    const wrapped = originalEnhanceMiddleware ? originalEnhanceMiddleware(middleware, metroServer) : middleware;
    return (req, res, next) => {
      if (req.url === '/__design/save' && req.method === 'POST') {
        readBody(req)
          .then((body) => {
            const parsed = JSON.parse(body);
            const { screen, values } = parsed || {};
            if (typeof screen !== 'string' || !SCREEN_NAME_RE.test(screen)) {
              throw new Error('invalid screen name');
            }
            if (!values || typeof values !== 'object') {
              throw new Error('invalid values');
            }
            writeDesignConfig(screen, values);
            res.statusCode = 200;
            res.setHeader('Content-Type', 'application/json');
            res.end(JSON.stringify({ ok: true }));
          })
          .catch((err) => {
            res.statusCode = 400;
            res.setHeader('Content-Type', 'application/json');
            res.end(JSON.stringify({ ok: false, error: String(err && err.message ? err.message : err) }));
          });
        return;
      }
      return wrapped(req, res, next);
    };
  },
};

module.exports = config;
